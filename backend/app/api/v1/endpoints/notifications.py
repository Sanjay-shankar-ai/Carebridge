# Ephemeral in-memory store for short-lived (30s) single-use SSE handshake tickets
SSE_ONE_TIME_TICKETS: Dict[str, Dict[str, Any]] = {}


@router.post("/stream/ticket", response_model=ApiResponseEnvelope[Dict[str, Any]], summary="Obtain Short-Lived Single-Use SSE Handshake Ticket")
async def create_sse_stream_ticket(
    current_user: UserPrincipal = Depends(get_current_user)
):
    """
    Issues a short-lived (30s) opaque ticket for Server-Sent Events EventSource connection.
    Prevents leaking long-lived Bearer tokens in URL query parameters, proxy logs, and browser history.
    """
    now = time.time()
    # Expire old tickets
    expired = [t for t, data in SSE_ONE_TIME_TICKETS.items() if now - data["created_at"] > 60]
    for exp in expired:
        SSE_ONE_TIME_TICKETS.pop(exp, None)

    ticket = f"cb_sse_{uuid.uuid4().hex}"
    SSE_ONE_TIME_TICKETS[ticket] = {
        "user_id": str(current_user.user_id),
        "created_at": now
    }

    return ApiResponseEnvelope.success_response(
        data={"ticket": ticket, "expires_in_seconds": 30},
        message="One-time SSE ticket issued successfully."
    )


@router.get("/stream", summary="Real-Time Server-Sent Events Stream")
async def stream_notifications(
    request: Request,
    ticket: Optional[str] = Query(None, description="One-time ticket from /notifications/stream/ticket (Preferred secure method)"),
    token: Optional[str] = Query(None, description="Auth token (Deprecated: use ticket or Authorization header)"),
    last_event_id: Optional[str] = Query(None, alias="Last-Event-ID", description="Last received notification ID for reconnection")
):
    """
    Server-Sent Events endpoint for real-time notification streaming.
    Supports secure single-use tickets, Authorization headers, and automatic reconnection with unread replay.
    """
    user_id_str: Optional[str] = None

    # Option A: Single-Use Secure Ticket (Preferred for EventSource without headers)
    if ticket:
        now = time.time()
        ticket_data = SSE_ONE_TIME_TICKETS.pop(ticket, None)
        if ticket_data and (now - ticket_data["created_at"] <= 35):
            user_id_str = ticket_data["user_id"]
        else:
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid or expired SSE handshake ticket. Request a new ticket via POST /stream/ticket.",
                headers={"WWW-Authenticate": "Bearer"},
            )

    # Option B: Authorization Request Header (For fetch streams / custom EventSource)
    if not user_id_str:
        auth_header = request.headers.get("Authorization")
        if auth_header and auth_header.startswith("Bearer "):
            raw_token = auth_header.split(" ", 1)[1]
            payload = decode_access_token(raw_token)
            user_id_str = payload.get("sub")

    # Option C: Token Query Parameter (Legacy / Fallback)
    if not user_id_str and token:
        payload = decode_access_token(token)
        user_id_str = payload.get("sub")

    if not user_id_str:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Missing valid authentication. Provide Authorization header, single-use ticket, or token.",
            headers={"WWW-Authenticate": "Bearer"},
        )

    try:
        user_uuid = uuid.UUID(user_id_str)
    except ValueError:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid user ID in credentials")

    # 2. Subscribe to Broadcaster
    queue = await NotificationBroadcaster.subscribe(user_id_str)

    async def event_generator():
        try:
            # First: Send connection confirmed handshake
            handshake = json.dumps({"type": "connected", "user_id": user_id_str, "timestamp": datetime.now(timezone.utc).isoformat()})
            yield f"event: connected\ndata: {handshake}\n\n"

            # Reconnection Replay: If client reconnected with last_event_id, send any unread notifications created after it
            last_eid_uuid: Optional[uuid.UUID] = None
            if last_event_id:
                try:
                    last_eid_uuid = uuid.UUID(last_event_id)
                except ValueError:
                    pass

            with get_sync_db() as sync_db:
                unread = NotificationService.get_missed_notifications_for_reconnect(
                    db=sync_db,
                    user_id=user_uuid,
                    last_event_id=last_eid_uuid
                )
                for un in unread[:25]:
                    data_str = json.dumps(NotificationService.serialize_notification(un))
                    yield f"id: {un.id}\nevent: notification\ndata: {data_str}\n\n"

            # Ongoing loop: wait for newly broadcast events or emit periodic keep-alive
            while True:
                # Check for client disconnect
                if await request.is_disconnected():
                    break

                try:
                    # Wait up to 15 seconds for a new event
                    payload_data = await asyncio.wait_for(queue.get(), timeout=15.0)
                    notif_id = payload_data.get("id", str(uuid.uuid4()))
                    data_str = json.dumps(payload_data)
                    yield f"id: {notif_id}\nevent: notification\ndata: {data_str}\n\n"
                except asyncio.TimeoutError:
                    # Keep-alive heartbeat ping to prevent proxy/browser timeout
                    yield ": keep-alive\n\n"
        except asyncio.CancelledError:
            pass
        finally:
            await NotificationBroadcaster.unsubscribe(user_id_str, queue)

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        }
    )

