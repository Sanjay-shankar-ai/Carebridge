@router.post("/dead-letter/{notification_id}/recover", response_model=ApiResponseEnvelope[Dict[str, Any]], summary="Recover Dead-Letter Notification")
async def recover_dead_letter_notification(
    notification_id: uuid.UUID,
    current_user: UserPrincipal = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_db)
):
    """
    Internal administrative endpoint to re-queue a dead-lettered notification.
    Restricted to Care Coordinators.
    """
    if current_user.role not in ("care_coordinator", "coordinator"):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Forbidden: Only Care Coordinators may execute dead-letter outbox recovery."
        )

