router = APIRouter(prefix="/notifications", tags=["Notifications"])


class MarkReadRequest(BaseModel):
    is_read: bool = Field(default=True, description="Target read status")


class TestNotificationRequest(BaseModel):
    event_type: str = Field(default="appointment_reminder", description="Notification event type")
    title: str = Field(default="Test Clinical Notification", description="Title")
    message: str = Field(default="This is a test notification generated by CareBridge.", description="Body")
    priority: str = Field(default="normal", description="'normal', 'urgent', 'critical'")


@router.get("", response_model=ApiResponseEnvelope[List[Dict[str, Any]]], summary="List User Notifications")
async def list_notifications(
    unread_only: bool = Query(False, description="Filter for unread notifications only"),
    limit: int = Query(50, ge=1, le=100, description="Max notifications to retrieve"),
    offset: int = Query(0, ge=0, description="Offset for pagination"),
    current_user: UserPrincipal = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_db)
):
    """
    Retrieves notifications strictly belonging to the authenticated user.
    Prevents cross-patient and cross-role notification access.
    """
    stmt = (
        select(Notification)
        .where(Notification.user_id == current_user.user_id)
        .order_by(Notification.created_at.desc())
        .offset(offset)
        .limit(limit)
    )

    if unread_only:
        stmt = stmt.where(Notification.is_read == False)

    result = await db.execute(stmt)
    notifs = result.scalars().all()

    data = [NotificationService.serialize_notification(n) for n in notifs]
    return ApiResponseEnvelope.success_response(
        data=data,
        message=f"Retrieved {len(data)} notification(s)"
    )


@router.get("/unread-count", response_model=ApiResponseEnvelope[Dict[str, int]], summary="Get Unread Notification Count")
async def get_unread_count(
    current_user: UserPrincipal = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_db)
):
    """Returns the total number of unread notifications for the active user."""
    stmt = (
        select(func.count())
        .select_from(Notification)
        .where(Notification.user_id == current_user.user_id, Notification.is_read == False)
    )
    result = await db.execute(stmt)
    count = result.scalar() or 0

    return ApiResponseEnvelope.success_response(
        data={"unread_count": count},
        message=f"{count} unread notification(s)"
    )


@router.patch("/{notification_id}/read", response_model=ApiResponseEnvelope[Dict[str, Any]], summary="Mark Notification As Read")
async def mark_notification_read(
    notification_id: uuid.UUID,
    current_user: UserPrincipal = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_db)
):
    """
    Marks a single notification as read.
    Validates recipient ownership: users cannot modify other users' notifications.
    """
    stmt = select(Notification).where(Notification.id == notification_id)
    res = await db.execute(stmt)
    notif = res.scalar_one_or_none()

    if not notif:
        raise HTTPException(status_code=404, detail="Notification not found")

    # Strict ownership verification
    if str(notif.user_id) != str(current_user.user_id):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Forbidden: You do not have permission to modify this notification."
        )

    now = datetime.now(timezone.utc)
    notif.is_read = True
    notif.read_at = now
    await db.commit()
    await db.refresh(notif)

    return ApiResponseEnvelope.success_response(
        data=NotificationService.serialize_notification(notif),
        message="Notification marked as read"
    )


@router.post("/mark-all-read", response_model=ApiResponseEnvelope[Dict[str, int]], summary="Mark All Notifications As Read")
async def mark_all_notifications_read(
    current_user: UserPrincipal = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_db)
):
    """Marks all unread notifications for the authenticated user as read."""
    now = datetime.now(timezone.utc)
    stmt = (
        update(Notification)
        .where(Notification.user_id == current_user.user_id, Notification.is_read == False)
        .values(is_read=True, read_at=now)
    )
    res = await db.execute(stmt)
    await db.commit()
    affected = res.rowcount or 0

    return ApiResponseEnvelope.success_response(
        data={"marked_read": affected},
        message=f"Marked {affected} notification(s) as read"
    )


@router.post("/reminders/process", response_model=ApiResponseEnvelope[Dict[str, Any]], summary="Trigger Appointment Reminders Scan")
async def trigger_appointment_reminders_scan(
    hours_ahead: int = Query(48, ge=1, le=168, description="Lookahead window in hours"),
    current_user: UserPrincipal = Depends(get_current_user)
):
    """
    Admin/Coordinator/Doctor endpoint to trigger automated appointment reminders sweep.
    Employs idempotency to prevent duplicate reminders.
    """
    if current_user.role not in ("care_coordinator", "doctor", "clinician"):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Forbidden: Only healthcare providers and coordinators may trigger reminders sweep."
        )

    with get_sync_db() as db:
        res = NotificationService.scan_and_send_appointment_reminders(db, hours_ahead=hours_ahead)

    return ApiResponseEnvelope.success_response(
        data=res,
        message=f"Scanned appointments: {res['reminders_sent']} reminder(s) generated."
    )


